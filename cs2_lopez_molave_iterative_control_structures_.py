"""## Part 4: Loop Flow Control — `break` and `continue`

- `break` ends the **entire loop immediately**.
- `continue` skips the rest of the **current iteration** and moves to the next one.
"""

# break: stop when number reaches 4
for number in range(1, 8):
    if number == 4:
        break
    print(number)

print("The loop stopped.")

# continue: skip 4, but keep looping
for number in range(1, 8):
    if number == 4:
        continue
    print(number)

print("The loop completed.")

